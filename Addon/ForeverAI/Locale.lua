FG.localeWidgets = {}

function FG.ClientLocale()
    if type(GetLocale) == "function" then
        local ok, result = pcall(GetLocale)
        if ok and type(result) == "string" then return result end
    end
    return "enUS"
end

function FG:InitLanguage()
    local mode = self.db and self.db.language or "auto"
    if mode ~= "deDE" and mode ~= "enUS" and mode ~= "auto" then mode = "auto" end
    if self.db then self.db.language = mode end
    self.languageMode = mode
    local client = self.ClientLocale()
    self.locale = mode == "auto" and (client == "deDE" and "deDE" or "enUS") or mode
end

FG:InitLanguage()
function FG.T(key, ...)
    local text = FG.locale == "deDE" and key or FG.Translations[key] or key
    if select("#", ...) > 0 then return string.format(text, ...) end
    return text
end

function FG:BindText(widget, key)
    widget:SetText(self.T(key))
    if key ~= "" then self.localeWidgets[#self.localeWidgets+1] = {widget=widget, key=key} end
end

function FG:RefreshLocale()
    for _, binding in ipairs(self.localeWidgets) do binding.widget:SetText(self.T(binding.key)) end
    if self.languageButton then
        local prefix = self.languageMode == "auto" and "Auto: " or ""
        self.languageButton:SetText(prefix .. (self.locale == "deDE" and "DE" or "EN") .. " | DE/EN")
    end
    if self.transfer then
        self.transfer.checked = nil
        self.transfer.start:Disable()
        self:RefreshTransferLocale()
        self.transfer.preview:SetText(self.T("Vorhandener Text wurde beim Sprachwechsel beibehalten. Export bei Bedarf neu erzeugen."))
    end
    if self.RefreshAIControls then self:RefreshAIControls() end
    if self.UpdateLiveButton then self:UpdateLiveButton() end
    if self.optionMenu then self.optionMenu:Hide() end
    if self.RedrawChat then self:RedrawChat() end
    if self.searchFrame and self.RefreshSearchResults then self:RefreshSearchResults() end
    if self.RefreshDestination then self:RefreshDestination() end
    if self.nav then self:Tick() end
end

function FG:SetLanguage(value)
    local aliases = {auto="auto", automatisch="auto", automatic="auto", de="deDE", dede="deDE", deutsch="deDE", german="deDE", en="enUS", enus="enUS", engb="enUS", englisch="enUS", english="enUS"}
    local key = self.Normalize(value)
    local mode = aliases[key]
    if key == "" then
        self:Say(self.T("Sprache: %s (%s). Deutsch und Englisch werden immer erkannt.", self.T(self.locale == "deDE" and "Deutsch" or "Englisch"), self.languageMode == "auto" and self.T("Automatisch") or self.languageMode))
        self:Say(self.T("Sprache wählen: /fai sprache auto | de | en. Auswahl wird pro Charakter gespeichert."))
        return true
    end
    if not mode then self:Say(self.T("Sprache wählen: /fai sprache auto | de | en. Auswahl wird pro Charakter gespeichert.")); return false end
    self.db.language = mode
    self:InitLanguage()
    self:RefreshLocale()
    self:Say(self.T("Sprache: %s (%s). Deutsch und Englisch werden immer erkannt.", self.T(self.locale == "deDE" and "Deutsch" or "Englisch"), mode == "auto" and self.T("Automatisch") or mode))
    return true
end

function FG:CycleLanguage()
    local nextMode = self.languageMode == "auto" and "de" or self.languageMode == "deDE" and "en" or "auto"
    return self:SetLanguage(nextMode)
end
