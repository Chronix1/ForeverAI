const clean=(s,n)=>[...String(s??'').replace(/[\u0000-\u001f\u007f]/g,' ').trim()].slice(0,n).join('');
export function parseLiveRequest(raw){
 if(typeof raw!=='string'||Buffer.byteLength(raw)>2750)throw new AppError('live_invalid_packet');
 const m=/^FAI1;([0-9a-f]{10,32});([0-9]{1,5});([a-z]{2,20});([A-Za-z0-9_./:+@~\-]{1,180});([a-z]{3,12});(de|en);([^;]*);([^;]*)$/.exec(raw);
 if(!m)throw new AppError('live_invalid_packet');
 const id=Number(m[2]);if(!Number.isInteger(id)||id<1||id>65535)throw new AppError('live_invalid_id');
 let question,context;try{question=decodeURIComponent(m[7]);context=decodeURIComponent(m[8]);}catch{throw new AppError('live_bad_encoding');}
 if(!question||!question.trim()||Buffer.byteLength(question)>512||context.length>1200||/[\x00-\x08\x0b\x0c\x0e-\x1f]/.test(question+context))throw new AppError('live_bad_question');
 return {session:m[1],id,requestedProvider:m[3],model:m[4],effort:m[5],language:m[6],question,context};
}
export function cellsToBytes(cells){
 let acc=0,n=0;const out=[];
 for(const c of cells){if(!Number.isInteger(c)||c<0||c>7)throw new AppError('live_cell_bad');acc=acc*8+c;n+=3;
  while(n>=8){n-=8;out.push(Math.floor(acc/2**n)&255);acc%=2**n;}
 }
 return Buffer.from(out);
}
export function decodeCells(cells){
 const buf=cellsToBytes(cells);
 if(buf.length<8||buf[0]!==0xC7||buf[1]!==0x1A)throw new AppError('live_magic');
 const id=buf.readUInt16BE(2),len=buf.readUInt16BE(4);
 if(len>2750||buf.length<len+8)throw new AppError('live_length');
 let s1=0,s2=0;for(let i=2;i<6+len;i++){s1=(s1+buf[i])%255;s2=(s2+s1)%255;}
 if(buf[6+len]!==s1||buf[7+len]!==s2)throw new AppError('live_checksum');
 const request=parseLiveRequest(buf.subarray(6,6+len).toString('utf8'));
 if(id!==request.id)throw new AppError('live_id_mismatch');
 return request;
}
export function encodeCells(request){
 const p=Buffer.from(request,'utf8');if(p.length>2750)throw new AppError('live_length');
 const b=Buffer.alloc(8+p.length);b[0]=0xC7;b[1]=0x1A;b.writeUInt16BE(parseLiveRequest(request).id,2);b.writeUInt16BE(p.length,4);p.copy(b,6);
 let s1=0,s2=0;for(let i=2;i<6+p.length;i++){s1=(s1+b[i])%255;s2=(s2+s1)%255;}b[6+p.length]=s1;b[7+p.length]=s2;
 let n=0,acc=0;const cells=[];for(const byte of b){acc=acc*256+byte;n+=8;while(n>=3){n-=3;cells.push(Math.floor(acc/2**n)%8);acc%=2**n;}}
 if(n)cells.push(acc*2**(3-n));return cells;
}
export function luaString(s){
 let out='"';for(const b of Buffer.from(String(s),'utf8')){
  if(b>=32&&b<=126&&b!==34&&b!==92)out+=String.fromCharCode(b);
  else out+='\\'+String(b).padStart(3,'0');
 }return out+'"';
}
export function slotSource({session,id,status,provider,model,text,catalog}){
 if(!/^[0-9a-f]{10,32}$/.test(session)||!Number.isInteger(id)||id<1||id>65535||!['done','error'].includes(status))throw new AppError('live_reply_invalid');
 const safe=[...String(text??'').replace(/\r\n?/g,'\n').replace(/[\x00-\x09\x0b-\x1f\x7f]/g,' ')].slice(0,4800).join(''),p=clean(provider,30),m=clean(model,180);
 // Only inert Lua assignments. No functions, string interpolation, macros, and no arbitrary tables.
 const cat=typeof catalog==='string'&&Buffer.byteLength(catalog)<25000?(',catalog='+luaString(catalog)):'';
 return '-- ForeverAI live data slot, generated by the local companion.\nForeverAI_LiveSlot={schema=1,session='+luaString(session)+',id='+id+',status='+luaString(status)+',provider='+luaString(p)+',model='+luaString(m)+',text='+luaString(safe)+cat+'}\n';
}
export function slotName(n){if(!Number.isInteger(n)||n<1||n>SLOTS)throw new AppError('live_bad_slot');return `ForeverAI_R${String(n).padStart(3,'0')}`;}
export function signalName(id){return 'r'+String(((id-1)%SLOTS)+1).padStart(3,'0')+'.wav';}
